CREATE FUNCTION public.register_inspection_attachment(p_inspection_request_id uuid,p_id uuid,p_storage_path text,p_file_name text,p_file_size bigint)
RETURNS public.inspection_request_attachments LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE saved public.inspection_request_attachments;actual_size bigint;
BEGIN
 IF NOT public.can_edit_inspection_request(p_inspection_request_id) THEN RAISE EXCEPTION 'Request access required'; END IF;
 PERFORM 1 FROM public.inspection_requests WHERE id=p_inspection_request_id FOR UPDATE;
 IF EXISTS(SELECT 1 FROM public.inspection_requests WHERE id=p_inspection_request_id AND status IN ('proposal_requested','cancelled')) THEN RAISE EXCEPTION 'This inspection is closed for attachments'; END IF;
 IF p_id IS NULL OR p_storage_path IS NULL OR p_file_name IS NULL OR p_file_size IS NULL OR length(p_file_name) NOT BETWEEN 1 AND 255 OR p_file_size NOT BETWEEN 0 AND 26214400
 OR p_file_name !~* '\.(jpg|jpeg|png|webp|heic|heif|pdf|doc|docx|xls|xlsx|csv|txt)$'
 OR p_storage_path !~ ('^'||p_inspection_request_id::text||'/'||auth.uid()::text||'/'||p_id::text||'\.(jpg|jpeg|png|webp|heic|heif|pdf|doc|docx|xls|xlsx|csv|txt)$') THEN RAISE EXCEPTION 'Invalid attachment'; END IF;
 PERFORM pg_advisory_xact_lock(hashtextextended(p_id::text,0));
 SELECT * INTO saved FROM public.inspection_request_attachments WHERE id=p_id;
 IF FOUND THEN
 IF saved.inspection_request_id<>p_inspection_request_id OR saved.uploaded_by<>auth.uid() OR saved.storage_path<>p_storage_path OR saved.file_name<>p_file_name OR saved.file_size<>p_file_size THEN RAISE EXCEPTION 'Attachment ID already used'; END IF;RETURN saved;END IF;
 SELECT (metadata->>'size')::bigint INTO actual_size FROM storage.objects WHERE bucket_id='inspection-attachments' AND name=p_storage_path;
 IF actual_size IS NULL OR actual_size<>p_file_size THEN RAISE EXCEPTION 'Upload not confirmed; retry the file'; END IF;
 INSERT INTO public.inspection_request_attachments(id,inspection_request_id,uploaded_by,storage_path,file_name,file_size) VALUES(p_id,p_inspection_request_id,auth.uid(),p_storage_path,p_file_name,p_file_size) RETURNING * INTO saved;
 INSERT INTO public.inspection_request_audit(inspection_request_id,actor_id,action,details) VALUES(p_inspection_request_id,auth.uid(),'attachment_added',jsonb_build_object('file_name',p_file_name,'attachment_id',p_id));
 RETURN saved;
END;$$;

CREATE FUNCTION public.create_inspection_proposal_request(p_id uuid,p_expected_version integer)
RETURNS public.inspection_requests LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE r public.inspection_requests;p public.proposal_requests;
BEGIN
 SELECT * INTO r FROM public.inspection_requests WHERE id=p_id FOR UPDATE;
 IF NOT FOUND OR NOT public.can_edit_inspection_request(p_id) OR (r.assigned_to IS DISTINCT FROM auth.uid() AND NOT public.is_proposal_manager()) THEN RAISE EXCEPTION 'Assigned technician or office access required'; END IF;
 IF r.proposal_request_id IS NOT NULL THEN RETURN r; END IF;
 IF r.status<>'inspected' OR r.version IS DISTINCT FROM p_expected_version THEN RAISE EXCEPTION 'Save and confirm the inspection before creating its proposal request'; END IF;
 IF trim(r.findings)='' OR trim(r.measurements)='' OR trim(r.property_address)='' THEN RAISE EXCEPTION 'Inspection findings, measurements and property address are required for the proposal handoff'; END IF;
 -- Guarded handoff reuses the existing proposal intake and Daniela review gate.
 -- Only the assigned inspector or office may create it; missing pricing is never invented.
 INSERT INTO public.proposal_requests(created_by,salesperson_id,customer_name,property_name,service_address,project_contact_phone,project_contact_email,
 existing_lead_job_id,scope_of_work,measurements,salesperson_notes,priority)
 VALUES(auth.uid(),r.assigned_to,r.contact_name,r.contact_name,r.property_address,r.phone,r.email,coalesce(r.lead_id::text,''),r.findings,r.measurements,r.notes,
 CASE WHEN r.urgency IN ('High','Urgent') THEN 'high' ELSE 'normal' END) RETURNING * INTO p;
 PERFORM public.write_proposal_audit(p.id,'created','Created from inspection request IR-'||r.request_number);
 PERFORM public.submit_draft_proposal_handoff(p.id,false);
 UPDATE public.inspection_requests SET proposal_request_id=p.id,status='proposal_requested',updated_at=now(),version=version+1 WHERE id=p_id RETURNING * INTO r;
 RETURN r;
END;$$;
