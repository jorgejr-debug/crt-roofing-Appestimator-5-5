CREATE FUNCTION public.can_read_inspection_request(p_id uuid) RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path=public,pg_temp AS $$
 SELECT EXISTS(SELECT 1 FROM public.inspection_requests r WHERE r.id=p_id AND auth.uid() IS NOT NULL AND (
 r.created_by=auth.uid() OR (r.status<>'draft' AND (r.assigned_to=auth.uid() OR public.is_proposal_manager()
 OR (r.proposal_request_id IS NOT NULL AND public.can_access_proposal_request(r.proposal_request_id))))));
$$;
CREATE FUNCTION public.can_edit_inspection_request(p_id uuid) RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path=public,pg_temp AS $$
 SELECT EXISTS(SELECT 1 FROM public.inspection_requests r WHERE r.id=p_id AND auth.uid() IS NOT NULL AND (
 r.created_by=auth.uid() OR (r.status<>'draft' AND (r.assigned_to=auth.uid() OR public.is_proposal_manager()))));
$$;
