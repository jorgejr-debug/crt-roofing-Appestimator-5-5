CREATE FUNCTION public.audit_inspection_request() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
BEGIN
 INSERT INTO public.inspection_request_audit(inspection_request_id,actor_id,action,details)
 VALUES(NEW.id,auth.uid(),CASE WHEN TG_OP='INSERT' THEN 'created' WHEN OLD.status IS DISTINCT FROM NEW.status THEN 'status_changed' ELSE 'updated' END,
 jsonb_build_object('before',CASE WHEN TG_OP='INSERT' THEN NULL ELSE to_jsonb(OLD) END,'after',to_jsonb(NEW)));
 IF TG_OP='UPDATE' AND NEW.status<>'draft' AND OLD.status<>'draft' AND NEW.assigned_to IS DISTINCT FROM OLD.assigned_to AND NEW.assigned_to IS NOT NULL THEN
  INSERT INTO public.workflow_notifications(event_key,user_id,source_record_uid,kind,message)
  VALUES('inspection_reassigned:'||NEW.id||':'||NEW.version,NEW.assigned_to,NEW.id::text,'inspection_assignment','Inspection IR-'||NEW.request_number||' was assigned to you. Open the Inspection Request Center for customer details and files.') ON CONFLICT(event_key,user_id) DO NOTHING;
 END IF;
 RETURN NEW;
END;$$;
