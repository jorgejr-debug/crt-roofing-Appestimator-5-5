CREATE FUNCTION public.capture_crm_inspection_request() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE lead public.crm_leads;t public.company_tasks;technician uuid;
BEGIN
 IF EXISTS(SELECT 1 FROM public.inspection_requests WHERE lead_id=NEW.lead_id AND created_by=NEW.requested_by) THEN RETURN NEW; END IF;
 SELECT * INTO lead FROM public.crm_leads WHERE id=NEW.lead_id;
 SELECT * INTO t FROM public.company_tasks WHERE id=NEW.task_id;
 SELECT user_id INTO technician FROM public.company_task_assignees WHERE task_id=t.id ORDER BY assigned_at LIMIT 1;
 INSERT INTO public.inspection_requests(created_by,assigned_to,lead_id,task_id,status,contact_name,phone,email,property_address,notes,urgency,submitted_at)
 VALUES(NEW.requested_by,technician,lead.id,t.id,'new',coalesce(nullif(lead.contact_name,''),nullif(lead.company_name,''),lead.first_name||' '||lead.last_name),lead.phone,lead.email,lead.property_address,lead.quick_note,CASE WHEN t.priority IN ('high','urgent') THEN 'High' ELSE 'Normal' END,t.created_at);
 RETURN NEW;
END;$$;
REVOKE ALL ON FUNCTION public.capture_crm_inspection_request() FROM PUBLIC,anon,authenticated;
