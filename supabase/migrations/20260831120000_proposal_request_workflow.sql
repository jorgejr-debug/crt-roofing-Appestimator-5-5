CREATE OR REPLACE FUNCTION public.save_proposal_version(p_request_id uuid,p_sections jsonb,p_proposal_id text DEFAULT '',p_estimate_id text DEFAULT '',p_pdf_storage_path text DEFAULT '',p_finalize boolean DEFAULT false)
RETURNS public.proposal_versions LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE version public.proposal_versions; next_number integer;
BEGIN
  IF NOT (public.is_company_estimator() OR public.is_proposal_manager()) OR NOT public.can_access_proposal_request(p_request_id) THEN RAISE EXCEPTION 'Estimator access required'; END IF;
  IF jsonb_typeof(p_sections)<>'array' OR jsonb_array_length(p_sections)=0 THEN RAISE EXCEPTION 'At least one proposal section is required'; END IF;
  SELECT coalesce(max(version_number),0)+1 INTO next_number FROM public.proposal_versions WHERE proposal_request_id=p_request_id;
  INSERT INTO public.proposal_versions(proposal_request_id,version_number,proposal_id,estimate_id,pdf_storage_path,sections,finalized_at,finalized_by)
  VALUES(p_request_id,next_number,coalesce(p_proposal_id,''),coalesce(p_estimate_id,''),coalesce(p_pdf_storage_path,''),p_sections,CASE WHEN p_finalize THEN now() END,CASE WHEN p_finalize THEN auth.uid() END) RETURNING * INTO version;
  UPDATE public.proposal_requests SET status=CASE WHEN p_finalize THEN 'sales_review' ELSE 'drafting_proposal' END,updated_at=now() WHERE id=p_request_id;
  PERFORM public.queue_proposal_notification(p_request_id,(SELECT salesperson_id FROM public.proposal_requests WHERE id=p_request_id),'sales_review',CASE WHEN p_finalize THEN 'Proposal is ready for Sales Review.' ELSE 'A proposal draft was created.' END);
  PERFORM public.write_proposal_audit(p_request_id,CASE WHEN p_finalize THEN 'proposal_finalized' ELSE 'proposal_drafted' END,'Version '||next_number,version.id); RETURN version;
END;
$$;

CREATE OR REPLACE FUNCTION public.approve_proposal_scope(p_version_id uuid,p_acknowledgement text)
RETURNS public.proposal_versions LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE version public.proposal_versions; request public.proposal_requests;
BEGIN
  SELECT * INTO version FROM public.proposal_versions WHERE id=p_version_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Proposal version not found'; END IF;
  SELECT * INTO request FROM public.proposal_requests WHERE id=version.proposal_request_id FOR UPDATE;
  IF request.salesperson_id<>auth.uid() AND NOT public.is_proposal_manager() THEN RAISE EXCEPTION 'Assigned salesperson approval required'; END IF;
  IF version.finalized_at IS NULL THEN RAISE EXCEPTION 'Proposal version is not finalized'; END IF;
  IF trim(coalesce(p_acknowledgement,'')) NOT LIKE 'I confirm that the scope,%' THEN RAISE EXCEPTION 'Scope acknowledgement is required'; END IF;
  UPDATE public.proposal_versions SET sales_approved_at=now(),sales_approved_by=auth.uid(),sales_acknowledgement=p_acknowledgement,updated_at=now() WHERE id=p_version_id RETURNING * INTO version;
  UPDATE public.proposal_requests SET status='ready_to_send',updated_at=now() WHERE id=request.id;
  PERFORM public.queue_proposal_notification(request.id,request.assigned_estimator_id,'sales_approved','Sales approved proposal version '||version.version_number||'.');
  PERFORM public.write_proposal_audit(request.id,'salesperson_approved',p_acknowledgement,version.id); RETURN version;
END;
$$;

CREATE OR REPLACE FUNCTION public.create_proposal_signing_session(p_version_id uuid,p_expires_hours integer DEFAULT 168)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE version public.proposal_versions; raw_token text:=encode(gen_random_bytes(32),'hex'); session_id uuid; expiry timestamptz;
BEGIN
  IF NOT (public.is_company_estimator() OR public.is_proposal_manager()) THEN RAISE EXCEPTION 'Estimator or management access required'; END IF;
  SELECT * INTO version FROM public.proposal_versions WHERE id=p_version_id;
  IF NOT FOUND OR NOT public.can_access_proposal_request(version.proposal_request_id) THEN RAISE EXCEPTION 'Proposal version not found'; END IF;
  IF version.sales_approved_at IS NULL THEN RAISE EXCEPTION 'Salesperson approval is required before sending'; END IF;
  expiry:=now()+make_interval(hours=>least(greatest(p_expires_hours,1),720));
  INSERT INTO public.proposal_signing_sessions(proposal_version_id,token_hash,expires_at,created_by)
  VALUES(version.id,encode(digest(raw_token,'sha256'),'hex'),expiry,auth.uid()) RETURNING id INTO session_id;
  UPDATE public.proposal_versions SET sent_at=coalesce(sent_at,now()),updated_at=now() WHERE id=version.id;
  UPDATE public.proposal_requests SET status='sent',sent_at=coalesce(sent_at,now()),updated_at=now() WHERE id=version.proposal_request_id;
  PERFORM public.write_proposal_audit(version.proposal_request_id,'proposal_sent','Secure signing link created',version.id,jsonb_build_object('signing_session_id',session_id,'expires_at',expiry));
  RETURN jsonb_build_object('token',raw_token,'expires_at',expiry,'proposal_version_id',version.id);
END;
$$;

-- Called only by the execute-proposal Edge Function with the service role after
-- validating the one-time token. Authenticated clients cannot execute it.
CREATE OR REPLACE FUNCTION public.complete_customer_proposal_decision(p_raw_token text,p_decision text,p_customer_name text,p_signature_path text,p_approved_section_ids text[] DEFAULT '{}')
RETURNS uuid LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE session public.proposal_signing_sessions; version public.proposal_versions; request public.proposal_requests; selected_sections jsonb;
BEGIN
  IF auth.role()<>'service_role' THEN RAISE EXCEPTION 'Service role required'; END IF;
  SELECT * INTO session FROM public.proposal_signing_sessions WHERE token_hash=encode(digest(p_raw_token,'sha256'),'hex') AND used_at IS NULL AND expires_at>now() FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Signing link is invalid or expired'; END IF;
  SELECT * INTO version FROM public.proposal_versions WHERE id=session.proposal_version_id FOR UPDATE;
  SELECT * INTO request FROM public.proposal_requests WHERE id=version.proposal_request_id FOR UPDATE;
  IF p_decision='signed' THEN
    IF trim(coalesce(p_signature_path,''))='' OR cardinality(p_approved_section_ids)=0 THEN RAISE EXCEPTION 'Signature and approved sections are required'; END IF;
    SELECT coalesce(jsonb_agg(section),'[]'::jsonb) INTO selected_sections FROM jsonb_array_elements(version.sections) section WHERE section->>'id'=ANY(p_approved_section_ids);
    IF jsonb_array_length(selected_sections)<>cardinality(p_approved_section_ids) THEN RAISE EXCEPTION 'Unknown proposal section selected'; END IF;
    UPDATE public.proposal_versions SET sections=(SELECT jsonb_agg(section||jsonb_build_object('customer_approved',(section->>'id'=ANY(p_approved_section_ids)))) FROM jsonb_array_elements(version.sections) section),customer_decision='signed',customer_name=trim(p_customer_name),customer_signature_storage_path=trim(p_signature_path),customer_signed_at=now(),updated_at=now() WHERE id=version.id RETURNING * INTO version;
    UPDATE public.proposal_requests SET status='signed',signed_at=now(),production_scope=jsonb_build_object('authorized',(SELECT coalesce(jsonb_agg(s),'[]'::jsonb) FROM jsonb_array_elements(version.sections) s WHERE coalesce((s->>'customer_approved')::boolean,false)),'not_authorized',(SELECT coalesce(jsonb_agg(s),'[]'::jsonb) FROM jsonb_array_elements(version.sections) s WHERE NOT coalesce((s->>'customer_approved')::boolean,false))),production_scope_generated_at=now(),updated_at=now() WHERE id=request.id;
  ELSIF p_decision='declined' THEN
    UPDATE public.proposal_versions SET customer_decision='declined',customer_name=trim(p_customer_name),customer_declined_at=now(),updated_at=now() WHERE id=version.id;
    UPDATE public.proposal_requests SET status='declined',declined_at=now(),updated_at=now() WHERE id=request.id;
  ELSE RAISE EXCEPTION 'Invalid customer decision'; END IF;
  UPDATE public.proposal_signing_sessions SET used_at=now() WHERE id=session.id;
  INSERT INTO public.proposal_request_audit_events(proposal_request_id,actor_id,action,notes,proposal_version_id,metadata)
  VALUES(request.id,NULL,'customer_'||p_decision,'Customer decision recorded through one-time signing link',version.id,jsonb_build_object('signing_session_id',session.id));
  INSERT INTO public.proposal_request_notifications(proposal_request_id,user_id,actor_id,notification_type,message)
  SELECT request.id,recipient,NULL,'proposal_'||p_decision,'Customer '||p_decision||' proposal version '||version.version_number||'.' FROM (SELECT request.salesperson_id recipient UNION SELECT request.assigned_estimator_id) recipients WHERE recipient IS NOT NULL;
  RETURN request.id;
END;
$$;
