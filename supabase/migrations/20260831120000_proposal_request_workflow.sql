CREATE OR REPLACE FUNCTION public.submit_proposal_request(p_request_id uuid)
RETURNS public.proposal_requests LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE request public.proposal_requests; missing text[]; estimator uuid; submitted_time timestamptz:=now(); task public.company_tasks;
BEGIN
  SELECT * INTO request FROM public.proposal_requests WHERE id=p_request_id FOR UPDATE;
  IF NOT FOUND OR (request.salesperson_id<>auth.uid() AND request.created_by<>auth.uid() AND NOT public.is_proposal_manager()) THEN RAISE EXCEPTION 'Not authorized'; END IF;
  IF request.status NOT IN ('draft','missing_information') THEN RAISE EXCEPTION 'Only draft or missing-information requests can be submitted'; END IF;
  missing:=public.proposal_request_required_missing(to_jsonb(request));
  IF cardinality(missing)>0 THEN RAISE EXCEPTION 'Required information is missing: %',array_to_string(missing,', '); END IF;
  IF request.priority='rush' AND request.rush_approval_status<>'approved' THEN
    UPDATE public.proposal_requests SET rush_approval_status='pending',updated_at=now() WHERE id=request.id RETURNING * INTO request;
    INSERT INTO public.proposal_request_notifications(proposal_request_id,user_id,actor_id,notification_type,message)
      SELECT request.id,id,auth.uid(),'rush_approval_needed','Rush Proposal Request #'||request.request_number||' requires approval.' FROM public.user_profiles WHERE lower(role) IN ('admin','cfo');
    PERFORM public.write_proposal_audit(request.id,'rush_approval_requested'); RETURN request;
  END IF;
  SELECT id INTO estimator FROM public.user_profiles WHERE lower(email)='daniela@crtroofing.com' LIMIT 1;
  estimator:=coalesce(request.assigned_estimator_id,estimator);
  IF estimator IS NULL THEN RAISE EXCEPTION 'No estimator is configured'; END IF;
  IF request.task_id IS NULL THEN
    INSERT INTO public.company_tasks(title,description,status,priority,due_date,related_type,related_id,related_label,created_by,task_type)
    VALUES('Proposal Request: '||request.property_name,request.scope_of_work,'open',CASE request.priority WHEN 'rush' THEN 'urgent' WHEN 'high' THEN 'high' ELSE 'normal' END,request.customer_deadline,'proposal_request',request.id::text,request.customer_name,request.created_by,'proposal_request') RETURNING * INTO task;
    INSERT INTO public.company_task_assignees(task_id,user_id,assigned_by) VALUES(task.id,estimator,auth.uid()) ON CONFLICT DO NOTHING;
  ELSE SELECT * INTO task FROM public.company_tasks WHERE id=request.task_id; END IF;
  UPDATE public.proposal_requests SET task_id=task.id,assigned_estimator_id=estimator,status='submitted',submitted_at=coalesce(submitted_at,submitted_time),
    target_completion_at=coalesce(manual_target_at,CASE job_type WHEN 'complex_commercial' THEN public.add_proposal_business_days(submitted_time,2) WHEN 'large_rfp' THEN manual_target_at ELSE public.add_proposal_business_days(submitted_time,1) END),
    sla_paused_seconds=sla_paused_seconds+CASE WHEN sla_paused_at IS NULL THEN 0 ELSE extract(epoch FROM submitted_time-sla_paused_at)::bigint END,sla_paused_at=NULL,missing_information_notes='',updated_at=now()
  WHERE id=request.id RETURNING * INTO request;
  PERFORM public.queue_proposal_notification(request.id,estimator,'proposal_submitted','A complete Proposal Request is ready for review.');
  PERFORM public.write_proposal_audit(request.id,CASE WHEN request.missing_information_count>0 THEN 'information_resubmitted' ELSE 'submitted' END);
  RETURN request;
END;
$$;

CREATE OR REPLACE FUNCTION public.review_proposal_request(p_request_id uuid,p_action text,p_missing_notes text DEFAULT '',p_target_at timestamptz DEFAULT NULL)
RETURNS public.proposal_requests LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE request public.proposal_requests;
BEGIN
  IF NOT (public.is_company_estimator() OR public.is_proposal_manager()) THEN RAISE EXCEPTION 'Estimator access required'; END IF;
  SELECT * INTO request FROM public.proposal_requests WHERE id=p_request_id FOR UPDATE;
  IF NOT FOUND OR request.status NOT IN ('submitted','under_review') THEN RAISE EXCEPTION 'Request is not awaiting review'; END IF;
  IF p_action='accept' THEN
    UPDATE public.proposal_requests SET status='under_review',accepted_at=now(),target_completion_at=coalesce(p_target_at,target_completion_at),updated_at=now() WHERE id=p_request_id RETURNING * INTO request;
    PERFORM public.write_proposal_audit(request.id,'assigned','Accepted into estimating queue');
  ELSIF p_action='missing_information' THEN
    IF trim(coalesce(p_missing_notes,''))='' THEN RAISE EXCEPTION 'Missing information details are required'; END IF;
    UPDATE public.proposal_requests SET status='missing_information',missing_information_notes=trim(p_missing_notes),missing_information_count=missing_information_count+1,sla_paused_at=now(),updated_at=now() WHERE id=p_request_id RETURNING * INTO request;
    PERFORM public.queue_proposal_notification(request.id,request.salesperson_id,'missing_information',trim(p_missing_notes));
    PERFORM public.write_proposal_audit(request.id,'information_requested',trim(p_missing_notes));
  ELSE RAISE EXCEPTION 'Invalid review action'; END IF;
  RETURN request;
END;
$$;

CREATE OR REPLACE FUNCTION public.approve_rush_proposal_request(p_request_id uuid,p_approved boolean,p_notes text DEFAULT '')
RETURNS public.proposal_requests LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE request public.proposal_requests;
BEGIN
  IF NOT public.is_proposal_manager() THEN RAISE EXCEPTION 'Admin/CFO access required'; END IF;
  UPDATE public.proposal_requests SET rush_approval_status=CASE WHEN p_approved THEN 'approved' ELSE 'rejected' END,rush_approved_by=auth.uid(),rush_approved_at=now(),priority=CASE WHEN p_approved THEN priority ELSE 'high' END,updated_at=now() WHERE id=p_request_id AND priority='rush' RETURNING * INTO request;
  IF NOT FOUND THEN RAISE EXCEPTION 'Rush request not found'; END IF;
  PERFORM public.queue_proposal_notification(request.id,request.salesperson_id,'rush_decision',CASE WHEN p_approved THEN 'Rush priority approved.' ELSE 'Rush priority rejected; request changed to High.' END);
  PERFORM public.write_proposal_audit(request.id,CASE WHEN p_approved THEN 'rush_approved' ELSE 'rush_rejected' END,p_notes); RETURN request;
END;
$$;

CREATE OR REPLACE FUNCTION public.manage_proposal_request(p_request_id uuid,p_estimator_id uuid DEFAULT NULL,p_priority text DEFAULT NULL,p_target_at timestamptz DEFAULT NULL)
RETURNS public.proposal_requests LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE request public.proposal_requests;
BEGIN
  IF NOT (public.is_company_estimator() OR public.is_proposal_manager()) THEN RAISE EXCEPTION 'Estimator or management access required'; END IF;
  IF p_estimator_id IS NOT NULL AND NOT public.is_proposal_manager() THEN RAISE EXCEPTION 'Only management can reassign requests'; END IF;
  IF p_priority IS NOT NULL AND p_priority NOT IN ('normal','high','rush') THEN RAISE EXCEPTION 'Invalid priority'; END IF;
