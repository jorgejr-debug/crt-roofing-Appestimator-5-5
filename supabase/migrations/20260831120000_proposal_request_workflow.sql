  IF p_category NOT IN ('photo','measurement','roof_report','drawing','rfp','customer_document','other') THEN RAISE EXCEPTION 'Invalid attachment category'; END IF;
  IF p_storage_path NOT LIKE p_request_id::text||'/%' THEN RAISE EXCEPTION 'Attachment path does not match Proposal Request'; END IF;
  INSERT INTO public.proposal_request_attachments(proposal_request_id,category,file_name,storage_path,content_type,file_size,uploaded_by)
  VALUES(p_request_id,p_category,trim(p_file_name),p_storage_path,coalesce(p_content_type,''),greatest(coalesce(p_file_size,0),0),auth.uid()) RETURNING * INTO result;
  PERFORM public.write_proposal_audit(p_request_id,'attachment_uploaded',result.file_name,NULL,jsonb_build_object('attachment_id',result.id,'category',result.category)); RETURN result;
END;
$$;

CREATE OR REPLACE FUNCTION public.create_change_order_signing_session(p_change_order_id uuid,p_expires_hours integer DEFAULT 168)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE change_order public.proposal_change_orders; raw_token text:=encode(gen_random_bytes(32),'hex'); expiry timestamptz;
BEGIN
  IF NOT (public.is_company_estimator() OR public.is_proposal_manager()) THEN RAISE EXCEPTION 'Estimator or management access required'; END IF;
  SELECT * INTO change_order FROM public.proposal_change_orders WHERE id=p_change_order_id;
  IF NOT FOUND OR NOT public.can_access_proposal_request(change_order.proposal_request_id) THEN RAISE EXCEPTION 'Change order not found'; END IF;
  expiry:=now()+make_interval(hours=>least(greatest(p_expires_hours,1),720));
  INSERT INTO public.proposal_change_order_signing_sessions(change_order_id,token_hash,expires_at,created_by)
  VALUES(change_order.id,encode(digest(raw_token,'sha256'),'hex'),expiry,auth.uid());
  UPDATE public.proposal_change_orders SET status='sent',updated_at=now() WHERE id=change_order.id;
  PERFORM public.write_proposal_audit(change_order.proposal_request_id,'change_order_sent',change_order.description,NULL,jsonb_build_object('change_order_id',change_order.id,'expires_at',expiry));
  RETURN jsonb_build_object('token',raw_token,'expires_at',expiry,'change_order_id',change_order.id);
END;
$$;

CREATE OR REPLACE FUNCTION public.complete_customer_change_order_signature(p_raw_token text,p_customer_name text,p_signature_path text)
RETURNS uuid LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE session public.proposal_change_order_signing_sessions; change_order public.proposal_change_orders; scope_entry jsonb;
BEGIN
  IF auth.role()<>'service_role' THEN RAISE EXCEPTION 'Service role required'; END IF;
  IF trim(coalesce(p_signature_path,''))='' OR trim(coalesce(p_customer_name,''))='' THEN RAISE EXCEPTION 'Customer name and signature are required'; END IF;
  SELECT * INTO session FROM public.proposal_change_order_signing_sessions WHERE token_hash=encode(digest(p_raw_token,'sha256'),'hex') AND used_at IS NULL AND expires_at>now() FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Signing link is invalid or expired'; END IF;
  UPDATE public.proposal_change_orders SET status='signed',customer_signature_storage_path=trim(p_signature_path),customer_signed_at=now(),updated_at=now() WHERE id=session.change_order_id RETURNING * INTO change_order;
  scope_entry:=jsonb_build_object('id',change_order.id,'title','Signed change order','scope',change_order.scope,'price',change_order.price,'customer_approved',true,'change_order',true);
  UPDATE public.proposal_requests SET production_scope=jsonb_set(production_scope,'{authorized}',coalesce(production_scope->'authorized','[]'::jsonb)||jsonb_build_array(scope_entry)),updated_at=now() WHERE id=change_order.proposal_request_id;
  UPDATE public.proposal_change_order_signing_sessions SET used_at=now() WHERE id=session.id;
  INSERT INTO public.proposal_request_audit_events(proposal_request_id,actor_id,action,notes,metadata)
  VALUES(change_order.proposal_request_id,NULL,'change_order_signed',change_order.description,jsonb_build_object('change_order_id',change_order.id,'customer_name',p_customer_name));
  RETURN change_order.proposal_request_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.set_proposal_deposit_satisfied(p_request_id uuid,p_satisfied boolean)
RETURNS public.proposal_requests LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE request public.proposal_requests;
BEGIN
  IF NOT (public.is_proposal_manager() OR public.is_company_estimator()) THEN RAISE EXCEPTION 'Estimator or management access required'; END IF;
  UPDATE public.proposal_requests SET deposit_satisfied_at=CASE WHEN p_satisfied THEN now() END,deposit_satisfied_by=CASE WHEN p_satisfied THEN auth.uid() END,updated_at=now()
  WHERE id=p_request_id AND public.can_access_proposal_request(id) RETURNING * INTO request;
  IF NOT FOUND THEN RAISE EXCEPTION 'Proposal request not found'; END IF;
  PERFORM public.write_proposal_audit(request.id,CASE WHEN p_satisfied THEN 'deposit_satisfied' ELSE 'deposit_reopened' END); RETURN request;
END;
$$;

CREATE OR REPLACE FUNCTION public.close_proposal_request(p_request_id uuid,p_notes text DEFAULT '')
RETURNS public.proposal_requests LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE request public.proposal_requests;
BEGIN
  SELECT * INTO request FROM public.proposal_requests WHERE id=p_request_id FOR UPDATE;
  IF NOT FOUND OR NOT public.can_access_proposal_request(p_request_id) THEN RAISE EXCEPTION 'Proposal request not found'; END IF;
  IF NOT (public.is_company_estimator() OR public.is_proposal_manager() OR request.salesperson_id=auth.uid()) THEN RAISE EXCEPTION 'Not authorized'; END IF;
  IF request.status NOT IN ('signed','declined') AND request.production_released_at IS NULL THEN RAISE EXCEPTION 'Only a completed or declined request can be closed'; END IF;
  UPDATE public.proposal_requests SET status='closed',closed_at=now(),updated_at=now() WHERE id=p_request_id RETURNING * INTO request;
  PERFORM public.write_proposal_audit(request.id,'closed',p_notes); RETURN request;
END;
$$;

CREATE OR REPLACE FUNCTION public.release_proposal_to_production(p_request_id uuid,p_override_reason text DEFAULT '')
RETURNS public.proposal_requests LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE request public.proposal_requests; version public.proposal_versions; blockers text[]:='{}'; override_used boolean:=false; new_job_id uuid; new_source_id text;
BEGIN
  IF NOT (public.is_company_estimator() OR public.is_proposal_manager()) THEN RAISE EXCEPTION 'Estimator or management access required'; END IF;
  SELECT * INTO request FROM public.proposal_requests WHERE id=p_request_id FOR UPDATE;
  IF NOT FOUND OR NOT public.can_access_proposal_request(p_request_id) THEN RAISE EXCEPTION 'Proposal request not found'; END IF;
  IF request.production_released_at IS NOT NULL THEN RETURN request; END IF;
  SELECT * INTO version FROM public.proposal_versions WHERE proposal_request_id=p_request_id ORDER BY version_number DESC LIMIT 1;
  IF version.finalized_at IS NULL THEN blockers:=array_append(blockers,'Proposal not finalized'); END IF;
  IF version.sales_approved_at IS NULL THEN blockers:=array_append(blockers,'Salesperson scope approval missing'); END IF;
  IF version.customer_decision<>'signed' OR version.customer_signed_at IS NULL THEN blockers:=array_append(blockers,'Customer signature missing'); END IF;
  IF request.production_scope_generated_at IS NULL OR jsonb_array_length(coalesce(request.production_scope->'authorized','[]'::jsonb))=0 THEN blockers:=array_append(blockers,'Authorized production scope missing'); END IF;
  IF request.deposit_required AND request.deposit_satisfied_at IS NULL THEN blockers:=array_append(blockers,'Required deposit not received'); END IF;
  IF EXISTS(SELECT 1 FROM public.proposal_change_orders WHERE proposal_request_id=p_request_id AND required_for_release AND status<>'signed') THEN blockers:=array_append(blockers,'Required change order not signed'); END IF;
  IF cardinality(blockers)>0 THEN
    IF NOT public.is_proposal_manager() OR trim(coalesce(p_override_reason,''))='' THEN RAISE EXCEPTION 'BLOCKED FROM PRODUCTION: %',array_to_string(blockers,'; '); END IF;
    override_used:=true;
  END IF;
  new_job_id:=gen_random_uuid(); new_source_id:='job:proposal-request:'||request.id;
  INSERT INTO public.active_jobs(id,user_key,source_record_uid,workflow_status,estimate_id,local_estimate_id,job_number,job_name,project_name,customer_name,customer,address,job_address,status,contract_amount,final_bid,project_contact,is_active,created_at,updated_at,updated_by,proposal_request_id,production_authorized_at,production_authorized_by,production_authorization_source,job_payload)
  VALUES(new_job_id,auth.uid()::text,new_source_id,'approved',version.estimate_id,version.estimate_id,'PR-'||request.request_number,request.property_name,request.property_name,request.customer_name,request.customer_name,request.service_address,request.service_address,'Ready for Production',coalesce(request.target_price,0),coalesce(request.target_price,0),request.customer_contact,true,now(),now(),auth.uid()::text,request.id,now(),auth.uid(),CASE WHEN override_used THEN 'admin_override' ELSE 'signed_proposal' END,
    jsonb_build_object('proposalRequestId',request.id,'proposalVersionId',version.id,'workflowStatus','approved','status','Ready for Production','projectStatus','Ready for Production','projectName',request.property_name,'customerName',request.customer_name,'projectAddress',request.service_address,'projectContact',concat_ws(' ',request.project_contact_first_name,request.project_contact_last_name),'projectContactPhone',request.project_contact_phone,'projectContactEmail',request.project_contact_email,'authorizedScope',request.production_scope->'authorized','notAuthorizedScope',request.production_scope->'not_authorized','productionGateOverride',override_used))
  ON CONFLICT(source_record_uid) DO UPDATE SET job_payload=EXCLUDED.job_payload,status=EXCLUDED.status,updated_at=now(),updated_by=auth.uid()::text RETURNING id INTO new_job_id;
  UPDATE public.proposal_requests SET production_released_at=now(),production_released_by=auth.uid(),production_override_reason=CASE WHEN override_used THEN trim(p_override_reason) ELSE '' END,active_job_id=new_job_id,updated_at=now() WHERE id=p_request_id RETURNING * INTO request;
  PERFORM public.write_proposal_audit(request.id,CASE WHEN override_used THEN 'production_override' ELSE 'production_released' END,CASE WHEN override_used THEN p_override_reason ELSE 'All release controls satisfied' END,version.id,jsonb_build_object('blockers',blockers,'active_job_id',new_job_id));
  IF override_used THEN
    INSERT INTO public.proposal_request_notifications(proposal_request_id,user_id,actor_id,notification_type,message)
    SELECT request.id,id,auth.uid(),'production_override','Production gate overridden: '||p_override_reason FROM public.user_profiles WHERE lower(role) IN ('admin','cfo') AND id<>auth.uid();
  END IF;
  RETURN request;
END;
$$;

-- This guard applies only to jobs created by the new proposal workflow. Legacy
-- and manually managed jobs retain their existing behavior during migration.
CREATE OR REPLACE FUNCTION public.block_unauthorized_proposal_production_start()
RETURNS trigger LANGUAGE plpgsql SET search_path=public,pg_temp AS $$
BEGIN
  IF NEW.proposal_request_id IS NOT NULL
    AND lower(coalesce(NEW.workflow_status,''))='active'
    AND (TG_OP='INSERT' OR lower(coalesce(OLD.workflow_status,''))<>'active')
    AND NEW.production_authorized_at IS NULL THEN
    RAISE EXCEPTION 'BLOCKED FROM PRODUCTION: signed or administratively authorized scope is required';
  END IF;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS trg_block_unauthorized_proposal_production_start ON public.active_jobs;
CREATE TRIGGER trg_block_unauthorized_proposal_production_start BEFORE INSERT OR UPDATE OF workflow_status ON public.active_jobs
FOR EACH ROW EXECUTE FUNCTION public.block_unauthorized_proposal_production_start();

