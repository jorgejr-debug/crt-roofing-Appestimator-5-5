CREATE OR REPLACE FUNCTION public.current_company_role()
RETURNS text LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $$
  SELECT lower(coalesce((SELECT role FROM public.user_profiles WHERE id = auth.uid()), ''));
$$;

CREATE OR REPLACE FUNCTION public.is_proposal_manager()
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $$
  SELECT public.current_company_role() IN ('admin', 'cfo');
$$;

CREATE OR REPLACE FUNCTION public.is_company_estimator()
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $$
  SELECT public.current_company_role() = 'estimator'
    OR lower(coalesce((SELECT email FROM public.user_profiles WHERE id = auth.uid()), auth.jwt() ->> 'email', '')) = 'daniela@crtroofing.com';
$$;

