CREATE OR REPLACE FUNCTION public.protect_proposal_notification_update()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
BEGIN
  IF auth.role()='service_role' THEN RETURN NEW; END IF;
  IF NEW.id IS DISTINCT FROM OLD.id OR NEW.proposal_request_id IS DISTINCT FROM OLD.proposal_request_id OR NEW.user_id IS DISTINCT FROM OLD.user_id
    OR NEW.actor_id IS DISTINCT FROM OLD.actor_id OR NEW.notification_type IS DISTINCT FROM OLD.notification_type OR NEW.message IS DISTINCT FROM OLD.message
    OR NEW.email_status IS DISTINCT FROM OLD.email_status OR NEW.email_sent_at IS DISTINCT FROM OLD.email_sent_at OR NEW.email_error IS DISTINCT FROM OLD.email_error
    OR NEW.created_at IS DISTINCT FROM OLD.created_at THEN RAISE EXCEPTION 'Users can only mark proposal notifications as read'; END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER trg_protect_proposal_notification_update BEFORE UPDATE ON public.proposal_request_notifications FOR EACH ROW EXECUTE FUNCTION public.protect_proposal_notification_update();

CREATE OR REPLACE FUNCTION public.enqueue_overdue_proposal_notifications()
RETURNS integer LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE inserted_count integer;
BEGIN
  IF auth.role()<>'service_role' THEN RAISE EXCEPTION 'Service role required'; END IF;
  INSERT INTO public.proposal_request_notifications(proposal_request_id,user_id,actor_id,notification_type,message)
  SELECT request.id,recipient,NULL,'proposal_overdue','Proposal Request #'||request.request_number||' is overdue.'
  FROM public.proposal_requests request
  CROSS JOIN LATERAL (SELECT request.salesperson_id recipient UNION SELECT request.assigned_estimator_id) recipients
  WHERE request.target_completion_at<now() AND request.status NOT IN ('sent','signed','declined','closed','missing_information') AND recipient IS NOT NULL
    AND NOT EXISTS(SELECT 1 FROM public.proposal_request_notifications notification WHERE notification.proposal_request_id=request.id AND notification.user_id=recipient AND notification.notification_type='proposal_overdue' AND notification.created_at>now()-interval '24 hours');
  GET DIAGNOSTICS inserted_count=ROW_COUNT; RETURN inserted_count;
END;
$$;
