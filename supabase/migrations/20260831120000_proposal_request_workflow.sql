CREATE OR REPLACE FUNCTION public.add_proposal_business_days(start_at timestamptz,day_count integer)
RETURNS timestamptz LANGUAGE plpgsql IMMUTABLE AS $$
DECLARE result timestamptz:=start_at; remaining integer:=greatest(day_count,0);
BEGIN
  WHILE remaining>0 LOOP
    result:=result+interval '1 day';
    IF extract(isodow FROM result)<6 THEN remaining:=remaining-1; END IF;
  END LOOP;
  RETURN result;
END;
$$;

